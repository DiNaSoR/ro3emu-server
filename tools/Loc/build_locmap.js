// Builds data/loc/loc_en.tsv, the map embedded in Ro3Emu.Loc.dll:
//   1. every re/loc/translation_queue.tsv row that already has English in the client's own tables (existing_en);
//   2. src/Ro3Emu.Loc/translations/*.tsv (our translations of the rest: "zh\ten" per line, same escaping), later files win.
// usage: node tools/Loc/build_locmap.js
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..', '..');
const out = path.join(root, 'data', 'loc', 'loc_en.tsv');
const cjk = /[⺀-鿿豈-﫿]/;

const unescape = s => s.replace(/\\(.)/g, (_, c) => (c === 't' ? '\t' : c === 'n' ? '\n' : c === 'r' ? '\r' : c));
const escape = s => s.replace(/\\/g, '\\\\').replace(/\t/g, '\\t').replace(/\r/g, '\\r').replace(/\n/g, '\\n');

function readTsv(file) {
  const lines = fs.readFileSync(file, 'utf8').replace(/^﻿/, '').split('\n');
  const header = lines.shift().replace(/\r$/, '').split('\t');
  return lines.filter(l => l.trim()).map(l => {
    const cells = l.replace(/\r$/, '').split('\t');
    return Object.fromEntries(header.map((h, i) => [h, unescape(cells[i] ?? '')]));
  });
}

const map = new Map();
let fromTables = 0, skipped = 0;
for (const row of readTsv(path.join(root, 're', 'loc', 'translation_queue.tsv'))) {
  const en = row.existing_en;
  if (!en || en === 'None' || cjk.test(en) || !cjk.test(row.text)) { if (en) skipped++; continue; }
  map.set(row.text, en);
  fromTables++;
}

// Every Localization_zh_CN / Localization_en pair: text that equals a table string (baked into a prefab or built
// from one) gets the client's own English. When one Chinese text has several English values, the most frequent wins.
// The queue's choices above and our translations below take precedence.
const locDir = process.env.RO3_LOCEXP || path.join(root, 'data', 'locexp');
let fromAllTables = 0;
if (fs.existsSync(path.join(locDir, 'Localization_zh_CN.json'))) {
  const zhTable = JSON.parse(fs.readFileSync(path.join(locDir, 'Localization_zh_CN.json'), 'utf8'));
  const enTable = JSON.parse(fs.readFileSync(path.join(locDir, 'Localization_en.json'), 'utf8'));
  const votes = new Map();
  for (const [key, row] of Object.entries(zhTable)) {
    const z = row && row._kDes, e = enTable[key] && enTable[key]._kDes;
    if (typeof z !== 'string' || typeof e !== 'string' || !cjk.test(z) || !e.trim() || e === 'None' || cjk.test(e)) continue;
    const v = votes.get(z) || new Map();
    v.set(e, (v.get(e) || 0) + 1);
    votes.set(z, v);
  }
  for (const [z, v] of votes) {
    if (map.has(z)) continue;
    map.set(z, [...v].sort((a, b) => b[1] - a[1])[0][0]);
    fromAllTables++;
  }
}
console.log(`client tables: +${fromAllTables} zh_CN/en pairs`);

const dir = path.join(root, 'src', 'Ro3Emu.Loc', 'translations');
let ours = 0;
if (fs.existsSync(dir)) {
  for (const f of fs.readdirSync(dir).filter(f => f.endsWith('.tsv')).sort()) {
    for (const line of fs.readFileSync(path.join(dir, f), 'utf8').replace(/^﻿/, '').split('\n')) {
      const l = line.replace(/\r$/, '');
      if (!l || l.startsWith('#')) continue;
      const tab = l.indexOf('\t');
      if (tab <= 0) continue;
      const zh = unescape(l.slice(0, tab)), en = unescape(l.slice(tab + 1)).trim();
      if (!en || cjk.test(en) || !cjk.test(zh)) continue;
      map.set(zh, en);
      ours++;
    }
  }
}

fs.mkdirSync(path.dirname(out), { recursive: true });
const body = ['# zh\ten - generated by tools/Loc/build_locmap.js, do not edit (edit src/Ro3Emu.Loc/translations/*.tsv)']
  .concat([...map].map(([zh, en]) => escape(zh) + '\t' + escape(en)));
fs.writeFileSync(out, body.join('\n') + '\n', 'utf8');
console.log(`${out}: ${map.size} entries (${fromTables} from client tables, ${ours} ours, ${skipped} table rows skipped)`);

// Prefab sids that exist in no Localization table render empty:
// data/loc/loc_sids.tsv maps sid -> the Chinese baked into the prefab, which Ro3Loc.Sid then maps to English.
const sids = new Map();
for (const row of readTsv(path.join(root, 're', 'loc', 'prefab_text.tsv'))) {
  if (row.class !== 'auto-sid-missing') continue;
  const sid = row.sid.trim();
  if (!/^\d+$/.test(sid) || sid === '0' || !row.text) continue;
  if (!sids.has(sid)) sids.set(sid, row.text);
}
const sidOut = path.join(root, 'data', 'loc', 'loc_sids.tsv');
fs.writeFileSync(sidOut, ['# sid\tzh - generated by tools/Loc/build_locmap.js'].concat([...sids].map(([s, z]) => s + '\t' + escape(z))).join('\n') + '\n', 'utf8');
console.log(`${sidOut}: ${sids.size} sids`);
